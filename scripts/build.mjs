import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'src');
const include = /<!--\s*include:\s*([^\s]+)\s*-->/g;

async function render(file, parents = []) {
  const path = resolve(source, file);
  if (!path.startsWith(source + sep)) throw new Error(`Include outside src: ${file}`);
  if (parents.includes(path)) throw new Error(`Circular include: ${[...parents, path].map(p => relative(source, p)).join(' -> ')}`);
  const input = await readFile(path, 'utf8');
  const parts = [];
  let end = 0;
  for (const match of input.matchAll(include)) {
    parts.push(input.slice(end, match.index));
    parts.push(await render(match[1], [...parents, path]));
    end = match.index + match[0].length;
  }
  parts.push(input.slice(end));
  return parts.join('');
}

try {
  const output = '<!-- Generated by node scripts/build.mjs. Edit src/ files instead. -->\n' + await render('index.html');
  const target = resolve(root, 'index.html');
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('index.html is out of date. Run npm run build.');
    console.log('index.html matches src/.');
  } else {
    await writeFile(target, output, 'utf8');
    console.log('Built index.html from src/.');
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
